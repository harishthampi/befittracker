"""
Builds supabase/seed/indb_foods.sql from the Indian Nutrient Databank (INDB).

INDB: 1,014 commonly eaten Indian recipes with nutrients per 100 g and per serving,
calculated from India's official food composition tables (ICMR-NIN IFCT 2017/2004),
with UK and USDA data filling gaps.
  Paper: Vincent et al., "Development of an Indian Food Composition Database",
         Current Developments in Nutrition, 2024 (open access, CC BY 4.0)
         https://pmc.ncbi.nlm.nih.gov/articles/PMC11277795/
  Data:  https://github.com/lindsayjaacks/Indian-Nutrient-Databank-INDB-  (INDB.xlsx)

Usage (only needed if INDB publishes an update; the generated SQL is already in the repo):
    pip install openpyxl
    python scripts/indb/build_seed.py path/to/INDB.xlsx supabase/seed/indb_foods.sql

What the script does, row by row:
  1. Reads per-100 g energy, protein, carbs, fat and fibre. Uses kJ / 4.184 when kcal is missing.
  2. Skips rows with no energy, impossible values, or calories that don't match their
     macros (see consistent()). Skipped rows are listed in the report so they can be checked.
  3. Works out the serving weight from (kcal per serving / kcal per 100 g) x 100, and offers
     it as "1 bowl (257 g)" only when it is a believable single portion (5-600 g).
  4. Writes one idempotent INSERT ... ON CONFLICT so the file can be re-run safely.
"""

import json
import re
import sys

import openpyxl

MIN_SERVING_G = 5
MAX_SERVING_G = 600


def num(v):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    return x if x == x else None  # drop NaN


def consistent(kcal, protein, carbs, fat, fibre):
    """
    Atwater check: energy should be close to 4*protein + 4*carbs + 9*fat + 2*fibre.
    INDB carbs are 'available carbohydrate', so fibre adds ~2 kcal/g.
    Allow 25% or 40 kcal of slack, whichever is larger, for rounding and alcohol/polyols.
    """
    expected = 4 * protein + 4 * carbs + 9 * fat + 2 * fibre
    return abs(kcal - expected) <= max(40, 0.25 * max(kcal, expected))


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def clean_name(s):
    return re.sub(r"\s+", " ", str(s)).strip()[:200]


def main(src, out):
    wb = openpyxl.load_workbook(src, read_only=True)
    rows = list(wb.worksheets[0].iter_rows(values_only=True))
    head = rows[0]
    ix = {c: i for i, c in enumerate(head)}

    kept, skipped = [], []
    for r in rows[1:]:
        code = str(r[ix["food_code"]] or "").strip()
        name = clean_name(r[ix["food_name"]] or "")
        if not code or not name:
            continue

        kcal = num(r[ix["energy_kcal"]])
        if not kcal:
            kj = num(r[ix["energy_kj"]])
            kcal = kj / 4.184 if kj else None
        protein = num(r[ix["protein_g"]]) or 0.0
        carbs = num(r[ix["carb_g"]]) or 0.0
        fat = num(r[ix["fat_g"]]) or 0.0
        fibre = num(r[ix["fibre_g"]]) or 0.0

        if not kcal or kcal <= 0:
            skipped.append((code, name, "no energy value"))
            continue
        if kcal > 950 or any(v < 0 or v > 100 for v in (protein, carbs, fat, fibre)):
            skipped.append((code, name, f"out of range ({kcal:.0f} kcal/100 g)"))
            continue
        if not consistent(kcal, protein, carbs, fat, fibre):
            expected = 4 * protein + 4 * carbs + 9 * fat + 2 * fibre
            skipped.append((code, name, f"calories {kcal:.0f} vs macros {expected:.0f} per 100 g"))
            continue

        servings = []
        per_serving_kcal = num(r[ix["unit_serving_energy_kcal"]])
        unit = clean_name(r[ix["servings_unit"]] or "")
        if per_serving_kcal and unit:
            grams = per_serving_kcal / kcal * 100
            if MIN_SERVING_G <= grams <= MAX_SERVING_G:
                servings.append({"label": f"1 {unit} ({round(grams)} g)"[:60], "grams": round(grams, 1)})

        kept.append(
            {
                "code": code,
                "name": name,
                "kcal": round(kcal, 2),
                "protein": round(protein, 2),
                "carbs": round(carbs, 2),
                "fat": round(fat, 2),
                "fibre": round(fibre, 2),
                "servings": servings,
            }
        )

    lines = [
        "-- Indian Nutrient Databank (INDB) recipes for BeFitTracker.",
        "-- Generated by scripts/indb/build_seed.py. Do not edit by hand.",
        "-- Source: https://github.com/lindsayjaacks/Indian-Nutrient-Databank-INDB- (open access, CC BY 4.0 paper)",
        f"-- {len(kept)} foods imported, {len(skipped)} skipped (see scripts/indb/skipped.txt).",
        "-- Run AFTER supabase/migrations/0002_indb_source.sql. Safe to re-run.",
        "",
        "insert into public.foods (owner_id, source, source_id, name, brand, kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g, servings)",
        "values",
    ]
    values = []
    for f in kept:
        values.append(
            "  (null, 'indb', {code}, {name}, null, {kcal}, {protein}, {carbs}, {fat}, {fibre}, {servings}::jsonb)".format(
                code=sql_str(f["code"]),
                name=sql_str(f["name"]),
                kcal=f["kcal"],
                protein=f["protein"],
                carbs=f["carbs"],
                fat=f["fat"],
                fibre=f["fibre"],
                servings=sql_str(json.dumps(f["servings"], ensure_ascii=False)),
            )
        )
    lines.append(",\n".join(values))
    lines += [
        "on conflict (source, source_id) do update set",
        "  name = excluded.name,",
        "  kcal_100g = excluded.kcal_100g,",
        "  protein_100g = excluded.protein_100g,",
        "  carbs_100g = excluded.carbs_100g,",
        "  fat_100g = excluded.fat_100g,",
        "  fiber_100g = excluded.fiber_100g,",
        "  servings = excluded.servings;",
        "",
    ]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    report = out.rsplit("/", 1)[0] + "/../../scripts/indb/skipped.txt"
    with open(report, "w", encoding="utf-8") as fh:
        fh.write(f"INDB rows skipped by build_seed.py ({len(skipped)}):\n\n")
        for code, name, why in skipped:
            fh.write(f"{code}\t{name}\t{why}\n")

    print(f"kept {len(kept)}, skipped {len(skipped)}")
    by_reason = {}
    for _, _, why in skipped:
        key = why.split(" ")[0]
        by_reason[key] = by_reason.get(key, 0) + 1
    print("skipped by reason:", by_reason)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: build_seed.py INDB.xlsx out.sql")
    main(sys.argv[1], sys.argv[2])
